		return FactionTreasureAdvanceRate[0]
	elseif RateNum < 1 and RateNum >= 0.8 then
		return FactionTreasureAdvanceRate[1]
	elseif RateNum < 0.8 and RateNum >= 0.5 then
		return FactionTreasureAdvanceRate[2]
	elseif RateNum < 0.5 and RateNum >= 0.3 then
		return FactionTreasureAdvanceRate[3]
	elseif RateNum < 0.3 and RateNum >= 0.1 then
		return FactionTreasureAdvanceRate[4]
	elseif RateNum < 0.1 and RateNum > 0 then
		return FactionTreasureAdvanceRate[5]
	elseif RateNum == 0 then
		return FactionTreasureAdvanceRate[6]
	end
end

