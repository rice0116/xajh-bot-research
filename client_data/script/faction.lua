	}
	local scene_id    = GameApi.GetSceneID()
	local npcstring1 = --[[!AUTO_467]]""
	local npcstring2 = --[[!AUTO_468]]""
	local length = 9999
	local flag = false

	for k,v in pairs(npclist) do
		if scene_id == k then
			npcstring1 = TaskHelp:GetTaskNpcLink(v[1],--[[!AUTO_469]]"幫派挑戰傳送師")
			npcstring2 = TaskHelp:GetTaskNpcLink(v[2],--[[!AUTO_470]]"幫派挑戰傳送師")
			return npcstring2,npcstring1
		end
	end

	if GuideInfo[scene_id] then
		for k,v in pairs(npclist) do
			if GuideInfo[scene_id][k] then
				if #GuideInfo[scene_id][k] < length then
					npcstring1 = TaskHelp:GetTaskNpcLink(v[1],--[[!AUTO_471]]"幫派挑戰傳送師")
					npcstring2 = TaskHelp:GetTaskNpcLink(v[2],--[[!AUTO_472]]"幫派挑戰傳送師")
					length = #GuideInfo[scene_id][k]
				end
			end
		end
		return npcstring2,npcstring1
	else
		return npcstring2,npcstring1
	end

	return npcstring2,npcstring1
end

