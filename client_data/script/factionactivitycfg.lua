function FactionActivityCfg:GetCfg (id,FactionType)
	local	facionActivityRemind = {

		icon = FactionActivityCfg[id].icon,
		desc = FactionActivityCfg[id].desc,
		NPCid = 0,
		}

	if	FactionType == 1 then
		facionActivityRemind.NPCid = FactionActivityCfg[id].NPCID1
	elseif FactionType == 3 then
		facionActivityRemind.NPCid = FactionActivityCfg[id].NPCID3
	else
		facionActivityRemind.NPCid = FactionActivityCfg[id].NPCID4
	
	end
	--LogPrint(Icon)
	return facionActivityRemind
end

function FactionActivityCfg:GetPromptCfg (id)
	return FactionActivityCfg.prompt
end

