	for k, v in pairs (SpringFestivalSignIn.DayInfo) do
		ret_table[#ret_table + 1] = os.time(v.begin_time)
	end
	
	return ret_table
end

function SpringFestivalSignIn:GetReceiveMoneyTime( )
	local ret_table = {}
	
