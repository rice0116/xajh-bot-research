function SpringFestivalSignIn:GetSignInfo()
	local ret_table = {}
	ret_table[#ret_table + 1] = self.sign_in_activity_tid
	ret_table[#ret_table + 1] = self.repu_cash_activity_tid
	ret_table[#ret_table + 1] = self.sign_in_seq
	ret_table[#ret_table + 1] = self.once_repu_cash
	ret_table[#ret_table + 1] = self.repu_cash_scale
	return unpack(ret_table);
end

function SpringFestivalSignIn:GetDayInfo()
	local ret_table = {}
	for k, v in pairs (self.DayInfo) do
		ret_table[#ret_table + 1] = v.index
		ret_table[#ret_table + 1] = v.award_tid
		ret_table[#ret_table + 1] = os.time(v.begin_time)
	end
	return unpack(ret_table);
end

