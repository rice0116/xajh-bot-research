--特殊处理表，需要特殊提示的相关文字内容可以填在这里
function FameNotice:GetNotice(FameID,ChangeCount,FinalCount)
	local NoticeContent

	if FameID == 194 or FameID == 195 then
		if ChangeCount == 2000 then
			return --[[!AUTO_513]]""
		end
	end


	if FameNotice[FameID].setting == 0 then
		NoticeContent = --[[!AUTO_514]]""
	elseif FameNotice[FameID].setting == 1 then
		if ChangeCount > 0 then
			NoticeContent = --[[!AUTO_515]]"獲得了"..ChangeCount..FameNotice[FameID].metrology..FameNotice[FameID].name..--[[!AUTO_516]]",目前擁有"..FameNotice[FameID].name..FinalCount..FameNotice[FameID].metrology..--[[!AUTO_517]]"."
			if FameID == 44 then --[[比武币]]
				NoticeContent = NoticeContent .. "每天最多獲取200點!"
			end
			if FameNotice[FameID].hint then
				GameApi.AddSystemHint(--[[!AUTO_518]]"^FFD44A" .. NoticeContent)
			end
		else
			LogPrint(--[[!AUTO_525]]"11111111111111111111111111111")
			NoticeContent = --[[!AUTO_519]]"失去了"..math.abs(ChangeCount)..FameNotice[FameID].metrology..FameNotice[FameID].name..--[[!AUTO_520]]",目前擁有"..FameNotice[FameID].name..FinalCount..FameNotice[FameID].metrology..--[[!AUTO_521]]"."
		end
	elseif FameNotice[FameID].setting == 2 then
		NoticeContent = FameNotice:SpecialMode(FameID,ChangeCount,FinalCount)
	elseif FameNotice[FameID].setting == 3 then
		NoticeContent = "本周已獲得"..FinalCount..FameNotice[FameID].metrology..FameNotice[FameID].name.."."
	else
		NoticeContent = --[[!AUTO_522]]""
	end
	--print(NoticeContent)
	return NoticeContent
end

function FameNotice:SpecialMode(FameID,ChangeCount,FinalCount)
	local SpecialContent
	if FameNotice.Special[FameID] then
		SpecialContent = --[[!AUTO_523]]"測試特殊聲望提示資訊"
	else
		SpecialContent = --[[!AUTO_524]]""
	end
	return SpecialContent
end

