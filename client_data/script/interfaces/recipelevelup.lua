-- 计算曲子中音符总数
function RecipeCount()
	local count = 0
	for i = 1, #Melody[2].Note do
		count = count + #Melody[2].Note[i]
	end
	return count
end

function Operation_RecipeLevelUp(idRecipe, recipeLevel, targetScore)
	math.randomseed(os.time())
	local operation_temp = {}
	local beatBpm = 60/(Melody[2].Bpm * (1 + recipeLevel/10)) -- 根据BPM获得每拍的具体时间
	local nobble_count = #Melody[2].Note								  -- 乐曲小节总数
	local temp_count = 6												  -- 音符表起始位置
	local Recipe_Count = RecipeCount()									  -- 音符总个数
	local totaltime = 0													  -- 歌曲总时长
	local scoreperfect = math.ceil((targetScore/Recipe_Count)*0.6)		  -- 最高判定分数算法
	local scoregood = math.ceil((targetScore/Recipe_Count)*0.4)			  -- 中级判定分数算法
	local scorebad = math.ceil((targetScore/Recipe_Count)*0.2)		      -- 最差判定分数算法

	--生成乐谱表初始设置
	operation_temp =
		{
			{ time = 0, 	type= Type.LIFETIME,	value=3000 },   			-- 音符存活时间
			{ time = 0, 	type= Type.PERFECTSCORE,value=scoreperfect },		-- 最高判定得分
			{ time = 0, 	type= Type.GOODSCORE,	value=scoregood },      	-- 中间判定得分
			{ time = 0, 	type= Type.BADSCORE, 	value=scorebad },			-- 最差判定得分
			{ time = 1000, 	type= Type.FIRE, 		value=0 },					-- 火力值
			{ time = 1000, 	type= Type.HINT,	 	value=--[[!AUTO_19]]"火候要求有變化了" }	--开始提示文字
		}

	-- 遍历乐谱生成乐谱表
	for i = 1, nobble_count do
		for v = 1, #Melody[2].Note[i] do
			temp_count = temp_count + 1
			operation_temp[temp_count] = {}
			if temp_count == 7 then
				totaltime = totaltime + 1 * 1000 * beatBpm + operation_temp[1].value
				operation_temp[temp_count].type = Type.MATERIAL
				operation_temp[temp_count].sfx = Melody[2].Note[i][v][2]
			elseif Melody[2].Note[i][v] == 0 then
				totaltime = totaltime + 1 * 1000 * beatBpm
				operation_temp[temp_count].type = Type.NULL
			else
				totaltime = totaltime + Melody[2].Note[i][v][1] * 1000 * beatBpm
				operation_temp[temp_count].type = Type.MATERIAL
				operation_temp[temp_count].sfx = Melody[2].Note[i][v][2]
			end
			operation_temp[temp_count].time = totaltime
			operation_temp[temp_count].value = RandomMat(idRecipe)
		end
	end

	operation_temp[temp_count + 1] = {}
	operation_temp[temp_count + 1].time = totaltime + 1000
	operation_temp[temp_count + 1].type = Type.END

	return operation_temp
end


