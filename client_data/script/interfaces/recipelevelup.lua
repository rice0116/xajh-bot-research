function GenerateRandom(m,n)
	math.randomseed(os.time());math.random();math.random()
	return math.random(m,n)
end

function GenerateRandomFire(m,n,seed)
	math.randomseed(seed);math.random();math.random()
	return math.random(m,n)
end

function ProduceTable(m,n,o,p)
	math.randomseed(os.time());math.random();math.random()
	for i = 1 ,100 do
		timepoint_table[i] = math.random(m,n)
		material_table[i] = math.random(o,p)
	end
end

function GetTime()
	local table_length = #timepoint_table
	local temp = timepoint_table[1]
	for i = 1,table_length do
		timepoint_table[i] = timepoint_table[i+1]
	end
	return temp
end

function GetMaterial()
	local table_length = #material_table
	local temp = material_table[1]
	for i = 1,table_length do
		material_table[i] = material_table[i+1]
	end
	return temp
end


function Material_Info_Recipe(idRecipe)
