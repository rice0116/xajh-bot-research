------------------------------------
function Win_HelpList:ShowDialog()
	DlgApi.ShowItem(self.this, --[[!AUTO_429]]"Txt_SearchText", false)
	DlgApi.ShowItem(self.this, --[[!AUTO_430]]"Btn_Search", false)
	DlgApi.ShowItem(self.this, --[[!AUTO_494]]"Img_Content", false)
	local ret = GameApi.GetPlayerFullProp(0)
	local index = 0
	if math.floor(ret.level/10) ~= 0 then
		index = math.floor(ret.level/10) - 1
	end
	self:DialogStateItemsShow(Win_HelpList_Cfg.State.INIT)
	DlgApi.CheckRadioButton(self.this, 1, index)
	DlgApi.CheckRadioButton(self.this, 2, 0)
	Win_HelpList_Cfg.CurLevelIndex = DlgApi.GetCheckedRadioButton(self.this, 1)
	self:SetTitleRdo()
	self:SetListContent(Win_HelpList_Cfg.CurLevelIndex, 0)
	self:SetPosition(--[[!AUTO_431]]"Rdp_SubTitle1", 0)
end

function Win_HelpList:ShowSelectHelpMsg(LevelIndex, TypeIndex, LineIndex)
	self:DialogStateItemsShow(Win_HelpList_Cfg.State.INIT)
	DlgApi.CheckRadioButton(self.this, 1, LevelIndex)
	DlgApi.CheckRadioButton(self.this, 2, TypeIndex)
	Win_HelpList_Cfg.CurLevelIndex = DlgApi.GetCheckedRadioButton(self.this, 1)
	self:SetTitleRdo()
	self:SetListContent(Win_HelpList_Cfg.CurLevelIndex, DlgApi.GetCheckedRadioButton(self.this, 2))
	self:SetPosition(--[[!AUTO_432]]"Rdp_SubTitle" .. TypeIndex + 1, TypeIndex)
	self:SetTextContent(LevelIndex, TypeIndex, LineIndex, 1)
	DlgApi.SetListCurLine (self.this, --[[!AUTO_433]]"List_Content", LineIndex - 1)
end

function Win_HelpList:ShowXIAOAOBAODIAN()
	DlgApi.ShowDialog(self.this, true)
	self:ShowSelectHelpMsg(6, 0, 1)
end

function Win_HelpList:CanShowBaoDian()
	return GameApi.GetTaskState(4573) == 3
end

