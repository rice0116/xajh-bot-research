-- 鼠标点击控件函数
------------------------------------
function Win_HelpList:OnLButtonDown(objName)
	if self:GetObjectName(objName, --[[!AUTO_490]]"Rdo_R") then
		self:DialogStateItemsShow(Win_HelpList_Cfg.State.INIT)
		local index = string.gsub(objName, --[[!AUTO_491]]"Rdo_R", --[[!AUTO_492]]"")
		DlgApi.CheckRadioButton(self.this, 1, tonumber(index) - 1)
		DlgApi.CheckRadioButton(self.this, 2, 0)
		Win_HelpList_Cfg.CurLevelIndex = DlgApi.GetCheckedRadioButton(self.this, 1)
		self:SetTitleRdo()
		self:SetListContent(Win_HelpList_Cfg.CurLevelIndex, 0)
		self:SetPosition(--[[!AUTO_493]]"Rdp_SubTitle1", 0)
		DlgApi.ShowItem(self.this, --[[!AUTO_494]]"Img_Content", false)
	end

	if self:GetObjectName(objName, --[[!AUTO_495]]"Rdp_SubTitle") then
		self:DialogStateItemsShow(Win_HelpList_Cfg.State.INIT)
		local index = string.gsub(objName, --[[!AUTO_496]]"Rdp_SubTitle", --[[!AUTO_497]]"")
		DlgApi.CheckRadioButton(self.this, 2, tonumber(index) - 1)

		Win_HelpList_Cfg.CurLevelIndex = DlgApi.GetCheckedRadioButton(self.this, 1)
		Win_HelpList_Cfg.CurTypeIndex  = tonumber(index) - 1
		self:SetTitleRdo()

		self:SetListContent(Win_HelpList_Cfg.CurLevelIndex, Win_HelpList_Cfg.CurTypeIndex)
		self:SetPosition(objName, tonumber(index) - 1)
		DlgApi.ShowItem(self.this, --[[!AUTO_494]]"Img_Content", false)
	end

	if self:GetObjectName(objName, --[[!AUTO_498]]"List_Content") then
		self:DialogStateItemsShow(Win_HelpList_Cfg.State.CHECKMESSAGE)
		self:onClick_List_Content()
	end

	if self:GetObjectName(objName, --[[!AUTO_499]]"Btn_Left") then
		self:DialogStateItemsShow(Win_HelpList_Cfg.State.BACKPAGE)
		Win_HelpList_Cfg.CurSubIndex = Win_HelpList_Cfg.CurSubIndex - 1
		self:onClick_PageBtn()
	end

	if self:GetObjectName(objName, --[[!AUTO_500]]"Btn_Right") then
		self:DialogStateItemsShow(Win_HelpList_Cfg.State.FRONTPAGE)
		Win_HelpList_Cfg.CurSubIndex = Win_HelpList_Cfg.CurSubIndex + 1
		self:onClick_PageBtn()
	end

	if self:GetObjectName(objName, --[[!AUTO_501]]"Txt_Text") then
		local x, y = GameApi.GetCursorPos()
		local linkIInfo = DlgApi.GetItemLink(self.this, --[[!AUTO_502]]"Txt_Text", x, y)
		if linkIInfo then
			TextLink:OnClickCustomLuaLink(linkIInfo)
		end
	end

	if self:GetObjectName(objName, --[[!AUTO_503]]"Btn_Search") then
		self:DialogStateItemsShow(Win_HelpList_Cfg.State.SEARCH)
		local text = DlgApi.GetItemText(self.this, --[[!AUTO_504]]"Txt_SearchText")
		if text ~= --[[!AUTO_505]]"" then
			self:SearchItemForName(text)
		end
	end
end

function Win_HelpList:SearchItemForName(SearchString)
	local itemString 	= --[[!AUTO_506]]""
	local ItemName 		= --[[!AUTO_507]]""
	local count 		= 1
	local i, j
	local temp
	Win_HelpList_Cfg.SearchList["name"] = {}
	Win_HelpList_Cfg.SearchList["id"]   = {}
	for k, v in pairs(ItemInfo) do
		if v["NpcSell"] or v["RecipeItem"] or v["MonsterLoot"] or v["Text"] then
			ItemName = GameApi.GetItemInfo(k)
			if ItemName and ItemName ~= --[[!AUTO_508]]"" then
				i, j = string.find(ItemName, SearchString)
				if i then
					table.insert(Win_HelpList_Cfg.SearchList["name"], count, ItemName)
					table.insert(Win_HelpList_Cfg.SearchList["id"], count, k)
				end
			end
		end
	end
	DlgApi.SetListText(self.this, --[[!AUTO_509]]"List_Content", Win_HelpList_Cfg.SearchList["name"])
	return
end

