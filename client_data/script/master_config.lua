function GetMasterConfig()
    local ret_table = {}
    for k,v in pairs(MasterConfig.Common) do
        ret_table[#ret_table + 1] = k
        ret_table[#ret_table + 1] = v.score
        ret_table[#ret_table + 1] = v.addon_group_id
        ret_table[#ret_table + 1] = v.item_count
    end
    return unpack(ret_table)
end

function GetCostRatio()
    local ret_table = {}
    for k,v in pairs(MasterConfig.Ratio) do
        ret_table[#ret_table + 1] = k
        ret_table[#ret_table + 1] = v.ratio
    end
    return unpack(ret_table)
end

function GetMasterCommonUseLimitId()
    return MasterConfig.common_use_limit_tid
end

