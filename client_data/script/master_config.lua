function MasterConfig:GetMasterCommonUseLimitTid()
    if MasterConfig.common_use_limit_tid then
        return MasterConfig.common_use_limit_tid
    else
        return 0
    end
end

function MasterConfig:GetStrengthenInfoByMasterLevel(level)
    if MasterConfig.Common[level] then
        return MasterConfig.Common[level].score, MasterConfig.Common[level].addon_group_id, MasterConfig.Common[level].item_count
    else
        return 0
    end
end

function MasterConfig:GetNeedItemCountWhenUpgrade(level,times)
    if MasterConfig.Ratio[times] and MasterConfig.Common[level] then
        return MasterConfig.Ratio[times].ratio * MasterConfig.Common[level].item_count
    else
        return 0
    end
end

function MasterConfig:GetNeedItemTidWhenUpgrade()
    if MasterConfig.need_item_tid then
        return MasterConfig.need_item_tid
    else
        return 0
    end
end

function MasterConfig:GetMaxMasterLevel()
	if MasterConfig.Common then
		return #MasterConfig.Common
	else
		return 0
	end
end
