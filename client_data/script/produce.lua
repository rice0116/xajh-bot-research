--传入表TBL,传出是否能合成 合成的物品表 提示文字
function Produce:ItemCombine(tbl)
	local putin_item = {}
	local getout_item = {}
	local flag1
	local flag2
	local title = --[[!AUTO_5]]"不滿足合成條件"
	local can_combine = false

	--整理放入的相同物品

	for i = 1,#tbl do
		if #putin_item < 1 then
			putin_item[1]={}
			putin_item[1].id = tbl[i].id
			putin_item[1].num = tbl[i].num
			putin_item[1].bind = tbl[i].bind
		else
			flag1 = false
			for j = 1 ,#putin_item do
				if tbl[i].id ~= 0 and tbl[i].id == putin_item[j].id and tbl[i].bind == putin_item[j].bind then
					flag1 = true
					putin_item[j].num = putin_item[j].num + tbl[i].num
					break
				end
			end

			if flag1 == false then
				putin_item[#putin_item+1] = {}
				putin_item[#putin_item] = tbl[i]
			end
		end
	end
	--物品合成计算
	for i = 1,#putin_item do
		flag2 = false
		for j = 1,#Produce.ItemList do
			if putin_item[i].id == Produce.ItemList[j][1] and putin_item[i].num >= Produce.ItemList[j][3] then
				putin_item[#putin_item+1] = {}
				putin_item[#putin_item].id = Produce.ItemList[j][2]
				putin_item[#putin_item].num = math.floor(putin_item[i].num/Produce.ItemList[j][3])
				putin_item[#putin_item].bind = putin_item[i].bind
				putin_item[i].num = putin_item[i].num-putin_item[#putin_item].num*Produce.ItemList[j][3]
				can_combine = true
				flag2 = true
				title = string.format(Produce.ItemList[j][6],putin_item[#putin_item].num*Produce.ItemList[j][3],putin_item[#putin_item].num)
				break
			end
		end

		if flag2 == true then
			break
		end
	end
	--整理合成后的相同物品
	local count = 1
	local flag3
	for i = 1,#putin_item do
		if putin_item[i].num > 0 then
			flag3 = false
			if #getout_item > 1 then
				for j = 1,#getout_item do
					if getout_item[j].id == putin_item[i].id and getout_item[j].bind == putin_item[i].bind then
						getout_item[j].num = getout_item[j].num + putin_item[i].num
						flag3 = true
						break
					end
				end
			end

			if flag3 == false then
				getout_item[count] = putin_item[i]
				count = count+1
			end
		end
	end

	return can_combine,getout_item,title
end

