--返回最近的NPC的ID和位置

function TransHelper:GetNearestTransNPCInfo( InstID, HostX,HostY,HostZ)
	if TransNPC[InstID] == nil then
		return 0
	end

	local iNPC = 1
	local CurDistSqr = 99999
	for k,v in pairs(TransNPC[InstID]) do
		local Len = GetLengthSq( HostX,HostY,HostZ,v.x,v.y,v.z )
		if( Len<CurDistSqr ) then
			CurDistSqr = Len
			iNPC = k
		end
	end
	local ret = TransNPC[InstID][iNPC]
	return ret.ID,ret.x,ret.y,ret.z
end

