--返回地图间的相邻关系
function GetAdjInfo()
	local brief_adj_info = {}
	for map, adjs in pairs(AdjInfo) do
		brief_adj_info[#brief_adj_info + 1] = map
		local adj_maps = {}
		for adj_map, transbox_info in pairs(adjs) do
			if transbox_info.TransBox > 0 then
				adj_maps[#adj_maps + 1] = adj_map
				adj_maps[#adj_maps + 1] = transbox_info.TransBox
				adj_maps[#adj_maps + 1] = transbox_info.x
				adj_maps[#adj_maps + 1] = transbox_info.z
			end
		end
		brief_adj_info[#brief_adj_info + 1] = #adj_maps / 4
		for k,v in pairs(adj_maps) do
			brief_adj_info[#brief_adj_info + 1] = v
		end
	end
	return #brief_adj_info, unpack(brief_adj_info)
end

