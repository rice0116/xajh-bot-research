--老虎机接口
function LotteryDesc:GetTigerInfo(id_tiger,val_1,val_2,val_3)
	if val_1 == val_2== val_3 and val_3 == 8 then
		return --[[!AUTO_398]]"頭獎"
	elseif val_1 == val_2== val_3 then
		return --[[!AUTO_399]]"二等獎"
	elseif val_1 ==  val_3 and val_2 ~= val_3 then
		return --[[!AUTO_400]]"三等獎"
	elseif val_1 ==  val_2 or val_2 == val_3 then
		return --[[!AUTO_401]]"四等獎"
	elseif val_1 ~=  val_2 and val_2 ~= val_3 and val_3 ~= val_1 then
		return --[[!AUTO_402]]"末等獎"
	end
	return --[[!AUTO_403]]"老虎機介面"
