-- 获取物品名称
function LotteryDesc:GetItemName(tid)
	local sName, iQuality,iCid = GameApi.GetItemInfo(tid)
	if sName and iQuality and iCid then
		local sColor = ITEM_COLOR_DESC[iQuality+1] or ITEM_COLOR_DESC[1]
		return string.format(--[[!AUTO_391]]"%s%s", sColor,  sName)
	end
	return --[[!AUTO_392]]""
end

function LotteryDesc:GetItemListInfo(item_tbl)
	local left_text  = --[[!AUTO_393]]""
	local right_text = --[[!AUTO_394]]""
	for i=1,#item_tbl do
		left_text  = left_text..LotteryDesc:GetItemName(item_tbl[i][1])..--[[!AUTO_395]]"\r"
		right_text = right_text..string.format(--[[!AUTO_396]]"%d",item_tbl[i][2])..--[[!AUTO_397]]"\r"
	end
	LogPrint(left_text)
	LogPrint(right_text)
	return left_text,right_text
end

